    <p>Один код работает на обеих платформах. Основные технологии: <strong>Flutter</strong> и <strong>React Native</strong>.</p>

    <p><strong>Flutter</strong> (Google) — компилируется в нативный код, высокая производительность, собственный движок рендеринга. Отличается плавными анимациями и одинаковым видом на iOS и Android.</p>

    <p><strong>React Native</strong> (Meta) — использует JavaScript, рендерит нативные компоненты платформы. Большая экосистема, легче найти разработчиков.</p>

