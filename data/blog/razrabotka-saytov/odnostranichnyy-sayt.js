<li><strong>Корпоративный сайт</strong> — 10–50+ страниц с полной информацией о компании</li>
<li><strong>Интернет-магазин</strong> — каталог товаров, карточки, корзина, оформление заказа</li>
<li><strong>Информационный портал</strong> — блог, статьи, база знаний</li>
