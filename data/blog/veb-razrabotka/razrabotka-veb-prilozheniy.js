<p>Веб-приложение — это не сайт. Это полноценный программный продукт, который работает в браузере: обрабатывает данные, реагирует на действия пользователя в реальном времени, хранит состояние и взаимодействует с сервером. Google Docs, Figma, Trello, онлайн-банкинг, системы бронирования — всё это веб-приложения.</p>

