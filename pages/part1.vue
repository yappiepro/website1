      <p>Я основал сообщество «Нескучный Нетворкинг» — сегодня в нём 6 400+ человек. Прежде чем начать работать с другими, я провёл собственное исследование: проанализировал 294 поста и 6 408 комментариев в экспертных Telegram-каналах. Смотрел, что реально приводит к заявкам, а что просто создаёт видимость активности.</p>

