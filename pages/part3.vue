      <h2>Почему люди не получают результата, даже когда делают всё «по плану»</h2>

      <p>За несколько лет работы с экспертами я видел одну и ту же картину снова и снова. Человек прочитал правильные вещи. Понял логику. Начал делать. И — ничего.</p>

